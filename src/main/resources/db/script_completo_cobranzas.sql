    cr.monto                                       AS capital_prestado,
    cr.tasa_interes                                AS tasa_porcentaje,
    ROUND(cr.monto * cr.tasa_interes / 100, 2)    AS interes_total,
    cu.numero_cuota,
    cu.monto_cuota,
    p.monto                                        AS abono_recibido,
    p.fecha_pago
FROM creditos cr
INNER JOIN clientes    cl  ON cl.id  = cr.cliente_id
INNER JOIN cobradores  cob ON cob.id = cr.cobrador_id
INNER JOIN cuotas      cu  ON cu.credito_id = cr.id
INNER JOIN pagos       p   ON p.cuota_id    = cu.id
ORDER BY cob.nombre_cobrador, cr.id, cu.numero_cuota;

-- -----------------------------------------------------------------------------------------
-- 4.2. JOIN TIPO 2: LEFT JOIN (Agrupación con Conservación de Registros Nulos)
-- Propósito: Reportar el estado total de la cartera por cobrador (activos e inactivos).
--            Se asegura de listar todos los cobradores incluso si no tienen créditos asignados.
-- -----------------------------------------------------------------------------------------
SELECT
    cob.id                                                         AS cobrador_id,
    cob.nombre_cobrador,
    cob.username,
    cob.activo,
    COUNT(cr.id)                                                   AS total_creditos_asignados,
    COALESCE(SUM(cr.monto), 0)                                     AS total_capital_prestado,
    COALESCE(SUM(ROUND(cr.monto * cr.tasa_interes / 100, 2)), 0)    AS total_interes_esperado,
    COALESCE(SUM(cr.monto), 0)
      + COALESCE(SUM(ROUND(cr.monto * cr.tasa_interes / 100, 2)), 0)AS cartera_bruta_total
FROM cobradores cob
LEFT JOIN creditos cr ON cr.cobrador_id = cob.id
GROUP BY cob.id, cob.nombre_cobrador, cob.username, cob.activo
ORDER BY cartera_bruta_total DESC NULLS LAST;


-- =========================================================================================
-- SECCIÓN 5: SUBCONSULTAS DE TIPO DIFERENTE
-- =========================================================================================

-- -----------------------------------------------------------------------------------------
-- 5.1. SUBCONSULTA TIPO 1: Escalar en Cláusula WHERE
-- Propósito: Comparar el capital de cada crédito frente al promedio aritmético general
--            de la cartera, calculando la desviación positiva.
-- -----------------------------------------------------------------------------------------
SELECT
    cr.id                                          AS credito_id,
    cl.nombre_cliente,
    cr.monto                                       AS capital,
    cr.tasa_interes                                AS tasa_pct,
    ROUND(cr.monto * cr.tasa_interes / 100, 2)    AS interes,
    cr.estado,
    ROUND(cr.monto - (SELECT AVG(monto) FROM creditos), 2) AS exceso_sobre_promedio
FROM creditos cr
JOIN clientes cl ON cl.id = cr.cliente_id
WHERE cr.monto > (
    SELECT AVG(monto) FROM creditos  -- Subconsulta escalar que entrega un solo valor numérico
)
ORDER BY cr.monto DESC;

-- -----------------------------------------------------------------------------------------
-- 5.2. SUBCONSULTA TIPO 2: Correlacionada con Operador EXISTS
-- Propósito: Filtrar únicamente aquellos clientes que presentan morosidad
--            (tienen al menos una cuota PENDIENTE vencida a la fecha actual).
-- -----------------------------------------------------------------------------------------
SELECT
    cl.id              AS cliente_id,
    cl.nombre_cliente,
    cl.telefono_cliente
FROM clientes cl
WHERE EXISTS (
    SELECT 1
    FROM creditos cr
    JOIN cuotas cu ON cu.credito_id = cr.id
    WHERE cr.cliente_id = cl.id                      -- Correlación con el registro de la consulta externa
      AND cu.estado = 'PENDIENTE'
      AND cu.fecha_vencimiento < CURRENT_DATE
)
ORDER BY cl.nombre_cliente;


-- =========================================================================================
-- SECCIÓN 6: VISTAS (REGULAR Y MATERIALIZADA)
-- =========================================================================================

-- -----------------------------------------------------------------------------------------
-- 6.1. VISTA REGULAR (Cálculo dinámico en tiempo real para el día a día)
-- Propósito: Monitoreo operativo de cuotas en mora con cálculo de días vencidos.
-- -----------------------------------------------------------------------------------------
CREATE OR REPLACE VIEW vista_cuotas_vencidas AS
SELECT
    cu.id                                          AS cuota_id,
    cl.nombre_cliente,
    cl.telefono_cliente,
    cr.id                                          AS credito_id,
    cob.nombre_cobrador,
    cu.numero_cuota,
    cu.monto_cuota,
    cu.fecha_vencimiento,
    (CURRENT_DATE - cu.fecha_vencimiento)          AS dias_de_mora,
    cr.tasa_interes                                AS tasa_credito,
    ROUND(cr.monto * cr.tasa_interes / 100, 2)    AS interes_credito
FROM cuotas cu
JOIN creditos   cr  ON cr.id  = cu.credito_id
JOIN clientes   cl  ON cl.id  = cr.cliente_id
JOIN cobradores cob ON cob.id = cr.cobrador_id
WHERE cu.estado = 'PENDIENTE'
  AND cu.fecha_vencimiento < CURRENT_DATE;

-- Consulta de prueba para la vista regular
SELECT * FROM vista_cuotas_vencidas ORDER BY dias_de_mora DESC;

-- -----------------------------------------------------------------------------------------
-- 6.2. VISTA MATERIALIZADA (Snapshot optimizado en disco para analítica financiera)
-- Propósito: Resumen consolidado de cartera y validación de la condición de refinanciamiento:
--            Determina si el total recaudado cubre el interés total del crédito.
-- -----------------------------------------------------------------------------------------
DROP MATERIALIZED VIEW IF EXISTS vista_resumen_creditos;

CREATE MATERIALIZED VIEW vista_resumen_creditos AS
SELECT
    cr.id                                                       AS credito_id,
    cl.nombre_cliente,
    cob.nombre_cobrador,
    cr.frecuencia_pago,
    cr.monto                                                    AS capital_prestado,
    cr.tasa_interes                                             AS tasa_pct,
    ROUND(cr.monto * cr.tasa_interes / 100, 2)                 AS interes_generado,
    cr.monto + ROUND(cr.monto * cr.tasa_interes / 100, 2)       AS total_a_recaudar,
    cr.estado                                                   AS estado_credito,
    COALESCE(SUM(cu.monto_cuota), 0)                           AS suma_cuotas_programadas,
    COALESCE(SUM(pag.total_pagado), 0)                         AS total_recaudado,
    COALESCE(SUM(cu.monto_cuota), 0) - COALESCE(SUM(pag.total_pagado), 0) AS saldo_pendiente,
    -- REGLA CRÍTICA DE REFINANCIAMIENTO:
    -- El deudor solo puede refinanciar si ya ha cubierto la totalidad del interés generado
    CASE
        WHEN COALESCE(SUM(pag.total_pagado), 0) >= ROUND(cr.monto * cr.tasa_interes / 100, 2)
        THEN TRUE
        ELSE FALSE
    END                                                         AS interes_cubierto_apto_refinanciar
FROM creditos cr
JOIN clientes   cl  ON cl.id  = cr.cliente_id
JOIN cobradores cob ON cob.id = cr.cobrador_id
LEFT JOIN cuotas cu ON cu.credito_id = cr.id
LEFT JOIN (
    SELECT cuota_id, SUM(monto) AS total_pagado
    FROM pagos
    GROUP BY cuota_id
) pag ON pag.cuota_id = cu.id
GROUP BY cr.id, cl.nombre_cliente, cob.nombre_cobrador,
         cr.frecuencia_pago, cr.monto, cr.tasa_interes, cr.estado
WITH DATA;

-- Índice único requerido para refrescar la vista concurrentemente sin bloquear lectores
CREATE UNIQUE INDEX idx_mv_resumen_creditos ON vista_resumen_creditos (credito_id);

-- Consulta de prueba para la vista materializada
SELECT * FROM vista_resumen_creditos ORDER BY saldo_pendiente DESC;

