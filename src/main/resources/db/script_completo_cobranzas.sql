-- =========================================================================================
-- SECCIÓN 1: CREACIÓN DE TABLAS Y RESTRICCIONES (DDL)
-- =========================================================================================

-- Limpieza preventiva
DROP VIEW IF EXISTS vista_cuotas_vencidas CASCADE;
DROP MATERIALIZED VIEW IF EXISTS vista_resumen_creditos CASCADE;
DROP TABLE IF EXISTS pagos CASCADE;
DROP TABLE IF EXISTS gestiones_cobro CASCADE;
DROP TABLE IF EXISTS cuotas CASCADE;
DROP TABLE IF EXISTS creditos CASCADE;
DROP TABLE IF EXISTS cobradores CASCADE;
DROP TABLE IF EXISTS clientes CASCADE;

-- 1.1. Tabla: clientes (Deudores)
CREATE TABLE clientes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cliente VARCHAR(150) NOT NULL,
    telefono_cliente VARCHAR(30),
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 1.2. Tabla: cobradores (Agentes de cobranza con credenciales de acceso para la App)
CREATE TABLE cobradores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_cobrador VARCHAR(150) NOT NULL,
    telefono_cobrador VARCHAR(30),
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 1.3. Tabla: creditos (Obligaciones financieras asignadas a un único cobrador)
CREATE TABLE creditos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credito_origen_id INTEGER UNIQUE, -- Regla: Un crédito solo puede originar UN refinanciamiento activo
    cliente_id INTEGER NOT NULL,
    cobrador_id INTEGER NOT NULL,
    monto DECIMAL(12,2) NOT NULL CHECK (monto > 0),
    fecha_inicio DATE NOT NULL,
    fecha_limite DATE NOT NULL,
    frecuencia_pago VARCHAR(20) NOT NULL CHECK (frecuencia_pago IN ('DIARIA', 'SEMANAL', 'QUINCENAL', 'MENSUAL')),
    tasa_interes DECIMAL(5,2) NOT NULL DEFAULT 0.00 CHECK (tasa_interes IN (5.00, 10.00, 20.00)),
    estado VARCHAR(20) NOT NULL DEFAULT 'AL_DIA' CHECK (estado IN ('AL_DIA', 'PAGADO', 'REFINANCIADO')),
    CONSTRAINT chk_fechas_credito CHECK (fecha_limite > fecha_inicio)
);

-- 1.4. Tabla: cuotas (Plan de amortización que compone el crédito)
CREATE TABLE cuotas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credito_id INTEGER NOT NULL,
    numero_cuota INTEGER NOT NULL,
    monto_cuota DECIMAL(12,2) NOT NULL CHECK (monto_cuota > 0),
    fecha_vencimiento DATE NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'PAGADA')),
    CONSTRAINT uq_credito_cuota UNIQUE (credito_id, numero_cuota)
);

-- 1.5. Tabla: gestiones_cobro (Trazabilidad de visitas, llamadas y recordatorios en campo)
CREATE TABLE gestiones_cobro (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credito_id INTEGER NOT NULL,
    cuota_id INTEGER NOT NULL,
    fecha_gestion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo_gestion VARCHAR(30) NOT NULL CHECK (tipo_gestion IN ('LLAMADA', 'MENSAJE', 'VISITA')),
    resultado VARCHAR(100) NOT NULL,
    observaciones TEXT
);

-- 1.6. Tabla: pagos (Abonos reales recaudados por el cobrador)
CREATE TABLE pagos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuota_id INTEGER NOT NULL,
    gestion_cobro_id INTEGER,
    monto DECIMAL(12,2) NOT NULL CHECK (monto > 0),
    fecha_pago TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- -----------------------------------------------------------------------------------------
-- LLAVES FORÁNEAS (INTEGRIDAD REFERENCIAL)
-- -----------------------------------------------------------------------------------------
ALTER TABLE creditos
    ADD CONSTRAINT fk_creditos_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id) DEFERRABLE INITIALLY IMMEDIATE,
    ADD CONSTRAINT fk_creditos_cobrador FOREIGN KEY (cobrador_id) REFERENCES cobradores (id) DEFERRABLE INITIALLY IMMEDIATE,
    ADD CONSTRAINT fk_creditos_origen FOREIGN KEY (credito_origen_id) REFERENCES creditos (id) DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE cuotas
    ADD CONSTRAINT fk_cuotas_credito FOREIGN KEY (credito_id) REFERENCES creditos (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE gestiones_cobro
    ADD CONSTRAINT fk_gestiones_credito FOREIGN KEY (credito_id) REFERENCES creditos (id) DEFERRABLE INITIALLY IMMEDIATE,
    ADD CONSTRAINT fk_gestiones_cuota FOREIGN KEY (cuota_id) REFERENCES cuotas (id) DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE pagos
    ADD CONSTRAINT fk_pagos_cuota FOREIGN KEY (cuota_id) REFERENCES cuotas (id) DEFERRABLE INITIALLY IMMEDIATE,
    ADD CONSTRAINT fk_pagos_gestion FOREIGN KEY (gestion_cobro_id) REFERENCES gestiones_cobro (id) DEFERRABLE INITIALLY IMMEDIATE;


-- =========================================================================================
-- SECCIÓN 2: LÓGICA DE NEGOCIO EN BD - TRIGGER DE TASA POR DURACIÓN
-- =========================================================================================
-- REGLA: El cálculo del interés se determina estrictamente por la duración (días calendario):
--   • 7 días exactos          -> 5%
--   • 15 días exactos         -> 10%
--   • Un mes o más (>= 28 d)  -> 20%
-- =========================================================================================

CREATE OR REPLACE FUNCTION fn_calcular_tasa_interes()
RETURNS TRIGGER AS $$
DECLARE
    v_duracion_dias INTEGER;
BEGIN
    v_duracion_dias := NEW.fecha_limite - NEW.fecha_inicio;

    IF v_duracion_dias = 7 THEN
        NEW.tasa_interes := 5.00;
    ELSIF v_duracion_dias = 15 THEN
        NEW.tasa_interes := 10.00;
    ELSIF v_duracion_dias >= 28 THEN
        NEW.tasa_interes := 20.00;
    ELSE
        -- Por defecto si supera o se acerca a un mes comercial
        NEW.tasa_interes := 20.00;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_calcular_tasa_interes ON creditos;
CREATE TRIGGER trg_calcular_tasa_interes
    BEFORE INSERT OR UPDATE OF fecha_inicio, fecha_limite
    ON creditos
    FOR EACH ROW
    EXECUTE FUNCTION fn_calcular_tasa_interes();


