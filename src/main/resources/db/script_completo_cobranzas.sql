-- =========================================================================================
-- SECCIÓN 7: TRANSACCIÓN DE REFINANCIAMIENTO CON VALIDACIÓN DE INTERÉS
-- =========================================================================================
-- Esta transacción implementa en motor la lógica que ejecuta el cobrador en su App:
--   1. Bloqueo pesimista del crédito origen (FOR UPDATE) para evitar condiciones de carrera.
--   2. Verificación de estado: No debe estar ya 'REFINANCIADO' ni 'PAGADO'.
--   3. Verificación de unicidad: No debe existir ya un crédito derivado de este origen.
--   4. Cálculo del interés exigido según la duración del crédito.
--   5. Validación de recaudo: Si total_pagado < interes_requerido, se genera un ROLLBACK (RAISE EXCEPTION).
--   6. Si cumple, se marca el crédito origen como 'REFINANCIADO'.
--   7. Se crea el nuevo crédito encadenado manteniendo al mismo deudor y cobrador.
--   8. Se generan automáticamente las cuotas del nuevo crédito.
--   9. Se actualiza la vista materializada.
-- =========================================================================================

DO $$
DECLARE
    -- Parámetros de la operación
    p_credito_origen_id   INTEGER := 16;  -- ID del crédito a refinanciar
    p_dias_nuevo_plazo    INTEGER := 30;  -- Duración del nuevo crédito en días
    p_num_nuevas_cuotas   INTEGER := 2;   -- Número de cuotas para el nuevo crédito
    
    -- Variables internas
    v_credito             creditos%ROWTYPE;
    v_total_pagado        DECIMAL(12,2);
    v_interes_requerido   DECIMAL(12,2);
    v_nuevo_credito_id    INTEGER;
    v_fecha_inicio        DATE := CURRENT_DATE;
    v_fecha_limite        DATE;
    v_monto_cuota         DECIMAL(12,2);
    i                     INTEGER;
BEGIN
    -- Paso 1: Bloquear y obtener crédito origen
    SELECT * INTO v_credito
    FROM creditos
    WHERE id = p_credito_origen_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Error: Crédito número % no encontrado.', p_credito_origen_id;
    END IF;

    -- Paso 2: Validar estado actual
    IF v_credito.estado IN ('REFINANCIADO', 'PAGADO') THEN
        RAISE EXCEPTION 'El crédito % se encuentra en estado % y no admite refinanciación.',
            p_credito_origen_id, v_credito.estado;
    END IF;

    -- Paso 3: Validar que no tenga refinanciamiento activo (restricción 1 a 1 por eslabón)
    IF EXISTS (SELECT 1 FROM creditos WHERE credito_origen_id = p_credito_origen_id) THEN
        RAISE EXCEPTION 'El crédito % ya fue refinanciado previamente.', p_credito_origen_id;
    END IF;

    -- Paso 4: Calcular interés requerido del crédito origen
    v_interes_requerido := ROUND(v_credito.monto * v_credito.tasa_interes / 100, 2);

    -- Paso 5: Consultar total pagado a la fecha sobre las cuotas del crédito
    SELECT COALESCE(SUM(p.monto), 0)
    INTO v_total_pagado
    FROM pagos p
    JOIN cuotas cu ON cu.id = p.cuota_id
    WHERE cu.credito_id = p_credito_origen_id;

    -- Paso 6: Validación de regla de negocio
    IF v_total_pagado < v_interes_requerido THEN
        RAISE EXCEPTION 'Refinanciación denegada para el crédito %. Interés generado: $%, total pagado: $%. Falta abonar: $%.',
            p_credito_origen_id, v_interes_requerido, v_total_pagado, (v_interes_requerido - v_total_pagado);
    END IF;

    -- Paso 7: Actualizar estado del crédito origen
    UPDATE creditos
    SET estado = 'REFINANCIADO'
    WHERE id = p_credito_origen_id;

    -- Paso 8: Calcular fecha límite del nuevo crédito
    v_fecha_limite := v_fecha_inicio + (p_dias_nuevo_plazo || ' days')::INTERVAL;

    -- Paso 9: Insertar el nuevo crédito refinanciado (el trigger calcula automáticamente su tasa)
    INSERT INTO creditos (
        credito_origen_id,
        cliente_id,
        cobrador_id,
        monto,
        fecha_inicio,
        fecha_limite,
        frecuencia_pago,
        estado
    ) VALUES (
        p_credito_origen_id,
        v_credito.cliente_id,
        v_credito.cobrador_id,
        v_credito.monto,
        v_fecha_inicio,
        v_fecha_limite,
        v_credito.frecuencia_pago,
        'AL_DIA'
    )
    RETURNING id INTO v_nuevo_credito_id;

    -- Paso 10: Generar el nuevo plan de cuotas
    v_monto_cuota := ROUND(v_credito.monto / p_num_nuevas_cuotas, 2);

    FOR i IN 1..p_num_nuevas_cuotas LOOP
        INSERT INTO cuotas (
            credito_id,
            numero_cuota,
            monto_cuota,
            fecha_vencimiento,
            estado
        ) VALUES (
            v_nuevo_credito_id,
            i,
            v_monto_cuota,
            v_fecha_inicio + ((p_dias_nuevo_plazo / p_num_nuevas_cuotas) * i || ' days')::INTERVAL,
            'PENDIENTE'
        );
    END LOOP;

    -- Paso 11: Sincronizar vista materializada
    REFRESH MATERIALIZED VIEW vista_resumen_creditos;

    RAISE NOTICE '=====================================================';
    RAISE NOTICE 'REFINANCIAMIENTO APLICADO CON ÉXITO:';
    RAISE NOTICE 'Crédito anterior : % (marcado REFINANCIADO)', p_credito_origen_id;
    RAISE NOTICE 'Nuevo crédito    : % (estado AL_DIA)', v_nuevo_credito_id;
    RAISE NOTICE 'Capital renovado : $%', v_credito.monto;
    RAISE NOTICE 'Cuotas generadas : % de $%', p_num_nuevas_cuotas, v_monto_cuota;
    RAISE NOTICE '=====================================================';

END $$;


-- =========================================================================================
-- SECCIÓN 8: CONSULTAS DE VERIFICACIÓN E INTEGRIDAD FINAL
-- =========================================================================================

-- 8.1. Consulta Recursiva (CTE) para auditar toda la cadena genealógica de refinanciamientos
WITH RECURSIVE arbol_refinanciaciones AS (
    -- Raíz: Créditos originales que no provienen de ningún otro
    SELECT
        id AS credito_id,
        credito_origen_id,
        cliente_id,
        cobrador_id,
        monto,
        tasa_interes,
        estado,
        1 AS nivel_generacion
    FROM creditos
    WHERE credito_origen_id IS NULL

    UNION ALL

    -- Recursión: Créditos derivados sucesivamente
    SELECT
        cr.id,
        cr.credito_origen_id,
        cr.cliente_id,
        cr.cobrador_id,
        cr.monto,
        cr.tasa_interes,
        cr.estado,
        ar.nivel_generacion + 1
    FROM creditos cr
    JOIN arbol_refinanciaciones ar ON ar.credito_id = cr.credito_origen_id
)
SELECT
    nivel_generacion,
    credito_id,
    credito_origen_id,
    monto,
    tasa_interes AS tasa_pct,
    estado
FROM arbol_refinanciaciones
ORDER BY nivel_generacion, credito_id;

